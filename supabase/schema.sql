-- Run this script in Supabase Dashboard > SQL Editor.
create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  email text not null,
  interest text not null,
  message text default '',
  ip_address text,
  ip_location text,
  consent boolean not null default false,
  status text not null default 'New' check (status in ('New', 'Contacted', 'Qualified', 'Closed')),
  created_at timestamptz not null default now()
);

create index if not exists enquiries_created_at_idx
  on public.enquiries (created_at desc);

-- The API uses the Supabase service-role key on the server only.
-- Do not expose SUPABASE_SERVICE_ROLE_KEY in any NEXT_PUBLIC_ variable.
alter table public.enquiries enable row level security;

-- No public read/insert policy is intentionally created. Server-side API inserts
-- use the service role and bypass RLS. Add authenticated admin policies later.

-- Safe migration for projects where the enquiries table was created before the admin dashboard.
alter table public.enquiries add column if not exists status text not null default 'New';
alter table public.enquiries drop constraint if exists enquiries_status_check;
alter table public.enquiries add constraint enquiries_status_check check (status in ('New', 'Contacted', 'Qualified', 'Closed'));
